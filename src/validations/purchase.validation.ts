import { z } from "zod";

// Line item schema for purchase order
export const purchaseItemSchema = z.object({
  id: z.union([z.number(), z.string()]).optional(),
  productId: z.number().int().positive("Valid product ID required"),
  sku: z.string().optional(),
  productName: z.string().optional(),
  quantity: z.number().min(1, "Quantity must be at least 1"),
  unitCost: z.number().min(0, "Unit cost cannot be negative").optional(),
  discount: z.number().min(0).default(0).optional(),
  taxRate: z.number().min(0).default(8.25).optional(),
  lineTotal: z.number().min(0).optional(),
  receivedQuantity: z.number().min(0).default(0).optional(),
});

// Create purchase order schema
export const createPurchaseSchema = z.object({
  purchaseNumber: z.string().optional(), // Auto-generated by backend e.g. PO-2026-003
  supplierId: z.number().int().positive("Supplier ID is required"),
  supplierName: z.string().optional(), // Auto-resolved by backend from supplierId if omitted
  warehouseId: z.number().int().positive("Warehouse ID is required"),
  warehouseName: z.string().optional(), // Auto-resolved by backend from warehouseId if omitted
  purchaseDate: z.string().optional(),
  expectedDate: z.string().optional(),
  supplierInvoiceNumber: z.string().optional(),
  containerNumber: z.string().optional(),
  status: z
    .enum(["DRAFT", "ORDERED", "PARTIALLY_RECEIVED", "RECEIVED", "CANCELLED"])
    .default("DRAFT"),
  items: z
    .array(purchaseItemSchema)
    .min(1, "At least one item is required in purchase order"),
  subtotal: z.number().min(0).optional(),
  discount: z.number().min(0).default(0).optional(),
  tax: z.number().min(0).default(0).optional(),
  additionalCharges: z.number().min(0).default(0).optional(),
  grandTotal: z.number().min(0).optional(),
  amountPaid: z.number().min(0).default(0).optional(),
  balanceDue: z.number().min(0).optional(),
  notes: z.string().optional(),
});

// Update purchase order schema
export const updatePurchaseSchema = createPurchaseSchema.partial();
