import { z } from "zod";

// Invoice line item schema
export const invoiceLineItemSchema = z.object({
  id: z.union([z.number(), z.string()]).optional(),
  productId: z.number().int().positive("Valid product ID required"),
  sku: z.string().optional(),
  productName: z.string().optional(),
  quantity: z.number().min(1, "Quantity must be at least 1"),
  unitPrice: z.number().min(0, "Unit price cannot be negative").optional(),
  costPrice: z.number().min(0).optional(),
  discount: z.number().min(0).default(0).optional(),
  taxRate: z.number().min(0).default(8.25).optional(),
  lineTotal: z.number().min(0).optional(),
});

// Create sales invoice schema
export const createInvoiceSchema = z.object({
  invoiceNumber: z.string().optional(), // Auto-generated by backend e.g. INV-2026-003
  invoiceDate: z.string().optional(),
  dueDate: z.string().optional(),
  salesChannelId: z.number().optional(),
  salesChannel: z.string().optional(),
  salesChannelName: z.string().optional(),
  externalOrderId: z.string().optional(), // Online platform Order ID / Ref #
  quotationId: z.number().optional(),
  customerId: z.number().optional(),
  buyerName: z.string().min(2, "Customer / Buyer name is required").trim(),
  buyerEmail: z.string().email("Invalid buyer email").optional().or(z.literal("")),
  buyerPhone: z.string().optional(),
  billingAddress: z.string().optional(),
  shippingAddress: z.string().optional(),
  warehouseId: z.number().int().positive().optional().nullable(),
  warehouseName: z.string().optional(),
  items: z.array(invoiceLineItemSchema).min(1, "At least one product line item is required"),
  subtotal: z.number().min(0).optional(),
  discountTotal: z.number().min(0).default(0).optional(),
  taxTotal: z.number().min(0).default(0).optional(),
  shippingCharges: z.number().min(0).default(0).optional(),
  additionalCharges: z.number().min(0).default(0).optional(),
  grandTotal: z.number().min(0).optional(),
  amountPaid: z.number().min(0).default(0).optional(),
  balanceDue: z.number().min(0).optional(),
  paymentStatus: z.enum(["PAID", "PARTIALLY_PAID", "PENDING", "OVERDUE"]).default("PENDING").optional(),
  paymentMethod: z.enum(["CASH", "BANK_TRANSFER", "CREDIT_CARD", "UPI", "CHECK"]).optional(),
  status: z.enum(["DRAFT", "ISSUED", "CANCELLED"]).default("ISSUED").optional(),
  notes: z.string().optional(),
  termsAndConditions: z.string().optional(),
});

// Update sales invoice schema
export const updateInvoiceSchema = createInvoiceSchema.partial();
