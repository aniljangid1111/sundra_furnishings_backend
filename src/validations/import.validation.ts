import { z } from "zod";

// Expense head schema (Customs, Ocean Freight, Insurance, Port Handling)
export const importExpenseHeadSchema = z.object({
  id: z.union([z.number(), z.string()]).optional(),
  type: z.enum([
    "FREIGHT",
    "INSURANCE",
    "CUSTOMS",
    "PORT_HANDLING",
    "BROKERAGE",
    "OTHER",
  ]),
  description: z.string().min(1, "Description is required"),
  amount: z.number().min(0, "Expense amount cannot be negative"),
  allocationMethod: z.enum(["BY_VALUE", "BY_QUANTITY", "EQUAL"]).default("BY_VALUE"),
});

// Import product item schema
export const importItemSchema = z.object({
  id: z.union([z.number(), z.string()]).optional(),
  productId: z.number().int().positive("Product ID required"),
  sku: z.string().optional(),
  productName: z.string().optional(),
  quantity: z.number().min(1, "Quantity must be at least 1"),
  purchaseUnitCost: z.number().min(0, "Purchase unit cost cannot be negative"),
  purchaseTotalCost: z.number().min(0).optional(),
  allocatedExpense: z.number().min(0).default(0).optional(),
  totalLandedCost: z.number().min(0).optional(),
  landedUnitCost: z.number().min(0).optional(),
});

// Create import shipment schema
export const createImportSchema = z.object({
  importNumber: z.string().optional(), // Auto-generated by backend e.g. IMP-2026-002
  supplierId: z.number().optional().nullable(),
  supplierName: z.string().optional().nullable(),
  supplierInvoiceNumber: z.string().optional().nullable(),
  purchaseId: z.number().optional().nullable(),
  purchaseNumber: z.string().optional().nullable(),
  shipmentReference: z.string().optional().nullable(),
  importDate: z.string().optional(),
  warehouseId: z.number().optional().default(1),
  warehouseName: z.string().optional(),
  status: z
    .enum(["DRAFT", "PROCESSING", "REVIEW_REQUIRED", "COMPLETED", "CANCELLED"])
    .default("DRAFT"),
  items: z.array(importItemSchema).min(1, "At least one item is required in shipment"),
  expenseHeads: z.array(importExpenseHeadSchema).default([]),
  totalProductCost: z.number().min(0).optional(),
  totalAdditionalCosts: z.number().min(0).optional(),
  totalLandedCost: z.number().min(0).optional(),
  documentName: z.string().optional().nullable(),
  documentExtracted: z.boolean().default(false).optional(),
  notes: z.string().optional().nullable(),
});

// Update import shipment schema
export const updateImportSchema = createImportSchema.partial();

